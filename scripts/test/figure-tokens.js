#!/usr/bin/env node

/**
 * Generated post figures (scripts/figures/) are standalone SVGs shown with <img>, so they can't
 * read jonplummer.css. Each copies the site tokens it needs into its own <style>. This checks
 * every copy against the stylesheet's :root, the same token-to-declaration way critical-css.js
 * checks the first-paint shell.
 *
 * It deliberately does not regenerate figures: that would tie every fast run to fontkit and the
 * label font, and a library upgrade that nudged an outline would fail the suite for nothing.
 * Only the colors can drift from the site without anyone touching the figure.
 *
 * A generated figure (one carrying the "Generated by scripts/figures/" comment) that declares
 * none of the site tokens is a failure, not a pass: it means this parser stopped seeing them.
 */

const fs = require('fs');
const path = require('path');
const { SITE_TOKENS, readSiteTokens } = require('../figures/figure-utils');
const { addFile, addIssue } = require('../utils/test-results');
const { runTest } = require('../utils/test-runner-helper');

const ROOT = path.join(__dirname, '..', '..');
const IMAGES = path.join(ROOT, 'src', 'assets', 'images');
const MARKER = 'Generated by scripts/figures/';

function findSvgs(dir) {
  const found = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      found.push(...findSvgs(full));
    } else if (entry.name.endsWith('.svg')) {
      found.push(full);
    }
  }
  return found;
}

function normalize(value) {
  return value.replace(/\s+/g, ' ').trim();
}

/** The site-token declarations in a figure's <style>, by name. */
function readFigureTokens(svg) {
  const style = (svg.match(/<style>([\s\S]*?)<\/style>/) || [])[1] || '';
  const css = style.replace(/\/\*[\s\S]*?\*\//g, '');
  const tokens = {};
  for (const name of SITE_TOKENS) {
    const match = css.match(new RegExp(`--${name}\\s*:\\s*([^;]+);`));
    if (match) {
      tokens[name] = normalize(match[1]);
    }
  }
  return tokens;
}

function runChecks(result) {
  const site = readSiteTokens();
  const figures = findSvgs(IMAGES).filter((file) => fs.readFileSync(file, 'utf8').includes(MARKER));

  for (const file of figures) {
    const relative = path.relative(ROOT, file);
    const fileObj = addFile(result, relative, path.basename(file));
    const tokens = readFigureTokens(fs.readFileSync(file, 'utf8'));

    if (Object.keys(tokens).length === 0) {
      addIssue(fileObj, {
        type: 'figure-tokens',
        message: 'generated figure declares no site tokens in its <style>; the copy or this parser changed',
        ruleId: 'figure-tokens',
      });
      continue;
    }

    for (const [name, value] of Object.entries(tokens)) {
      if (value !== site[name]) {
        addIssue(fileObj, {
          type: 'figure-tokens',
          message:
            `--${name} is "${value}" but jonplummer.css has "${site[name]}" — ` +
            'run `pnpm run generate-figures` and commit the SVG',
          ruleId: 'figure-tokens',
        });
      }
    }
  }
}

runTest({
  testType: 'figure-tokens',
  testName: 'Figure token sync',
  requiresSite: false,
  validateFn: async (result) => {
    runChecks(result);
  },
});
