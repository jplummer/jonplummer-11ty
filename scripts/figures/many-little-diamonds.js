/**
 * Many little diamonds, for the 2026-10-09 post of that name.
 * A cloud of single diamonds ("frying pans": an immersion handle into generate-then-evaluate)
 * of many sizes, in front of the textbook double diamond. The four the post names are
 * called out; "Find the benefit" takes the accent and opens just before the double diamond does.
 */

const path = require('path');
const { readSiteTokens, rng, outlineText } = require('./figure-utils');

const W = 1200;
const H = 600;
const output = path.join(__dirname, '..', '..', 'src', 'assets', 'images', '2026', '10', 'many-little-diamonds.svg');

const LABEL_SIZE = 56; // near 12px at phone width; the spec's floor

// The pans the post names, placed by hand. Left vertex of "Find the benefit" (x=110) sits just
// before the double diamond's (x=140).
const NAMED = [
  { cx: 240, cy: 300, r: 130, h: 85, text: 'Find the benefit', side: 'below', accent: true },
  { cx: 600, cy: 420, r: 46, h: 40, text: 'Usability fix', side: 'below' },
  { cx: 930, cy: 370, r: 54, h: 50, text: 'Tech limit', side: 'below' },
  { cx: 945, cy: 215, r: 16, h: 10, text: 'Wording', side: 'right' },
];
// Neeman's diamond stays in the cloud, unlabeled: the post doesn't single it out as the only one
const FIXED_CROWD = [{ cx: 720, cy: 230, r: 80, h: 16 }];
const CROWD_SEED = 7;
const CROWD_COUNT = 16;

// Handle thickness follows the 2022 single-diamond drawing, about 0.37 r
function pan({ cx, cy, r, h }) {
  const t = r * 0.37 / 2;
  const n = (v) => Math.round(v * 10) / 10;
  return `M${n(cx - r - h)} ${n(cy - t)}L${n(cx - r + t)} ${n(cy - t)}L${n(cx)} ${n(cy - r)}L${n(cx + r)} ${n(cy)}L${n(cx)} ${n(cy + r)}L${n(cx - r + t)} ${n(cy + t)}L${n(cx - r - h)} ${n(cy + t)}Z`;
}

// Log-uniform sizes inside an elliptical cloud. Overlap is fine; piling isn't, so centers keep
// apart in proportion to size, and well clear of the named pans.
function crowd() {
  const random = rng(CROWD_SEED);
  const out = [];
  let tries = 0;
  while (out.length < CROWD_COUNT && tries++ < 5000) {
    const a = random() * Math.PI * 2;
    const d = Math.sqrt(random());
    const size = Math.exp(Math.log(8) + random() * (Math.log(110) - Math.log(8)));
    const p = { cx: 600 + Math.cos(a) * d * 470, cy: 300 + Math.sin(a) * d * 190, r: size, h: size * (0.15 + random() * 1.1) };
    const crowded = [...out, ...NAMED, ...FIXED_CROWD].some(
      (q) => Math.hypot(p.cx - q.cx, p.cy - q.cy) < (p.r + q.r) * (q.text ? 0.95 : 0.55)
    );
    if (!crowded) {
      out.push(p);
    }
  }
  return [...FIXED_CROWD, ...out].sort((a, b) => b.r - a.r);
}

function label(p) {
  if (p.side === 'below') {
    return outlineText(p.text, p.cx - p.h / 3, p.cy + p.r + 54, LABEL_SIZE, 'middle');
  }
  return outlineText(p.text, p.cx + p.r + 14, p.cy + 19, LABEL_SIZE);
}

// The textbook double diamond: two equal diamonds across the frame
function ghost() {
  const r = 240;
  const cy = 300;
  const x0 = 140;
  return `M${x0} ${cy}L${x0 + r} ${cy - r}L${x0 + 2 * r} ${cy}L${x0 + r} ${cy + r}Z` +
    `M${x0 + 2 * r} ${cy}L${x0 + 3 * r} ${cy - r}L${x0 + 4 * r} ${cy}L${x0 + 3 * r} ${cy + r}Z`;
}

function render() {
  const site = readSiteTokens();
  // Stacking: ghost, then the crowd, then the accent, then the other named pans. A stronger pan
  // never sits under a weaker one.
  const named = [...NAMED].sort((a, b) => (a.accent ? 0 : 1) - (b.accent ? 0 : 1));

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<!-- Generated by scripts/figures/many-little-diamonds.js (pnpm run generate-figures). Don't edit by hand. -->
<style>
:root {
  color-scheme: light dark;
  /* Copied from jonplummer.css :root; pnpm run test figure-tokens fails if these drift */
  --text-color: ${site['text-color']};
  --content-background-color: ${site['content-background-color']};
  --link-color: ${site['link-color']};
  --pan: color-mix(in oklch, var(--text-color) 45%, var(--content-background-color));
  --pan-named: color-mix(in oklch, var(--text-color) 70%, var(--content-background-color));
  /* oklab in dark: an oklch mix of red into grey swings through purple */
  --pan-accent: light-dark(color-mix(in oklch, var(--link-color) 75%, var(--content-background-color)), color-mix(in oklab, var(--link-color) 80%, var(--content-background-color)));
}
/* light-dark() takes colors only, so alpha that differs by mode lives in the colors.
   The double diamond is a faint haze in light and a shadow below the page in dark. */
.ghost { fill: light-dark(color-mix(in oklch, var(--text-color) 7%, transparent), oklch(12% 0.006 260deg)); }
/* The crowd is translucent so overlaps build up; stronger in dark so pans over the shadow don't sink */
.pan { fill: light-dark(color-mix(in oklch, var(--pan) 26%, transparent), color-mix(in oklch, var(--pan) 55%, transparent)); }
.named { fill: var(--pan-named); }
.accent { fill: var(--pan-accent); }
.label { fill: var(--text-color); }
.label-accent { fill: var(--link-color); }
</style>
<path class="ghost" d="${ghost()}"/>
${crowd().map((p) => `<path class="pan" d="${pan(p)}"/>`).join('\n')}
${named.map((p) => `<path class="${p.accent ? 'accent' : 'named'}" d="${pan(p)}"/>`).join('\n')}
${NAMED.map((p) => `<path class="label${p.accent ? ' label-accent' : ''}" d="${label(p)}"/>`).join('\n')}
</svg>
`;
}

module.exports = { output, render };
