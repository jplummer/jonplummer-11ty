/**
 * Same objects, two kinds of tools, for "Agentic AI doesn't make human interfaces go away" (2026-04-20).
 * A column of objects in the middle. On the right, the agent's tools are three pills; the active one's
 * line splits, outside the lens, to change two objects (dark). On the left, the interface is a
 * magnifying glass held over those same two objects: everything under the lens is drawn 1.4× (a
 * clipped, scaled copy of the scene), so the person is examining the very objects the agent changed.
 * People and agents use different tools on the same objects, and the interface is how a person sees
 * what the agent did.
 */

const path = require('path');
const { readSiteTokens, outlineText, roundedPolyline } = require('./figure-utils');

const W = 1200;
const H = 600;
const output = path.join(__dirname, '..', '..', 'src', 'assets', 'images', '2026', '04', 'same-objects.svg');

const LABEL_SIZE = 56; // near 12px at phone width; the spec's floor
const LABEL_Y = 588; // baseline for the labels under the objects and the tools

// Objects: a column, linked top to bottom. The agent changed the middle two.
const OBJ_X = 600;
const OBJ_YS = [120, 250, 350, 480];
const CHANGED = [1, 2];
const OBJ_SIZE = 64;

// Tools: three pills. Only the first is in use.
const TOOL_X0 = 860;
const TOOL_X1 = 1060;
const TOOL_YS = [190, 300, 410];
const TOOL_H = 64;
const SPLIT_X = 780; // right of the lens rim (which crosses the branches near x 731), so the split shows

// Lens
const LENS_X = 600;
const LENS_Y = 300;
const LENS_R = 140;
const MAGNIFY = 1.4;
const HANDLE_ANGLE = Math.PI / 6; // down-left, 30° below horizontal, into the empty left side
const HANDLE_LEN = 170;

const n = (v) => Math.round(v * 10) / 10;
const rect = (x0, y0, x1, y1, cls, r = 0) =>
  `<rect class="${cls}" x="${n(x0)}" y="${n(y0)}" width="${n(x1 - x0)}" height="${n(y1 - y0)}"${r ? ` rx="${r}"` : ''}/>`;

function scene() {
  const half = OBJ_SIZE / 2;
  const edge = OBJ_X + half;
  const [a, b] = CHANGED.map((i) => OBJ_YS[i]);
  return [
    `<path class="tie" d="M${OBJ_X} ${OBJ_YS[0]}V${OBJ_YS[OBJ_YS.length - 1]}"/>`,
    // The active tool's line turns down at the split and reaches the lower object; a branch reaches the upper
    `<path class="go" d="${roundedPolyline([[TOOL_X0, TOOL_YS[0]], [SPLIT_X, TOOL_YS[0]], [SPLIT_X, b], [edge, b]], 20)}M${SPLIT_X} ${a}H${edge}"/>`,
    ...OBJ_YS.map((y, i) => rect(OBJ_X - half, y - half, OBJ_X + half, y + half, CHANGED.includes(i) ? 'object' : 'object-quiet')),
    ...TOOL_YS.map((y, i) => rect(TOOL_X0, y - TOOL_H / 2, TOOL_X1, y + TOOL_H / 2, i === 0 ? 'object' : 'object-quiet', TOOL_H / 2)),
  ].join('\n');
}

function lens(content) {
  const dx = -Math.cos(HANDLE_ANGLE);
  const dy = Math.sin(HANDLE_ANGLE);
  const hx = LENS_X + (LENS_R + 4) * dx;
  const hy = LENS_Y + (LENS_R + 4) * dy;
  const ex = hx + HANDLE_LEN * dx;
  const ey = hy + HANDLE_LEN * dy;
  return {
    svg: [
      `<defs><clipPath id="same-objects-lens"><circle cx="${LENS_X}" cy="${LENS_Y}" r="${LENS_R}"/></clipPath></defs>`,
      `<g clip-path="url(#same-objects-lens)">`,
      `<circle class="lens" cx="${LENS_X}" cy="${LENS_Y}" r="${LENS_R}"/>`,
      `<g transform="translate(${LENS_X} ${LENS_Y}) scale(${MAGNIFY}) translate(${-LENS_X} ${-LENS_Y})">`,
      content,
      '</g>',
      '</g>',
      `<path class="handle" d="M${n(hx)} ${n(hy)}L${n(ex)} ${n(ey)}"/>`,
      `<circle class="rim" cx="${LENS_X}" cy="${LENS_Y}" r="${LENS_R}"/>`,
    ].join('\n'),
    labelX: ex - 30,
    labelY: ey + 30,
  };
}

function render() {
  const site = readSiteTokens();
  const content = scene();
  const glass = lens(content);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<!-- Generated by scripts/figures/same-objects.js (pnpm run generate-figures). Don't edit by hand. -->
<style>
:root {
  color-scheme: light dark;
  /* Copied from jonplummer.css :root; pnpm run test figure-tokens fails if these drift */
  --text-color: ${site['text-color']};
  --content-background-color: ${site['content-background-color']};
  --link-color: ${site['link-color']};
}
.object { fill: color-mix(in oklch, var(--text-color) 70%, var(--content-background-color)); }
.object-quiet { fill: color-mix(in oklch, var(--text-color) 30%, var(--content-background-color)); }
.tie { fill: none; stroke: color-mix(in oklch, var(--text-color) 45%, var(--content-background-color)); stroke-width: 4; }
.go { fill: none; stroke: color-mix(in oklch, var(--text-color) 70%, var(--content-background-color)); stroke-width: 8; stroke-linecap: round; }
/* The lens is opaque, so the magnified copy hides the scene under it */
.lens { fill: var(--content-background-color); }
.rim { fill: none; stroke: var(--link-color); stroke-width: 10; }
.handle { fill: none; stroke: var(--link-color); stroke-width: 28; stroke-linecap: round; }
.label { fill: var(--text-color); }
.label-accent { fill: var(--link-color); }
</style>
${content}
${glass.svg}
<path class="label-accent" d="${outlineText('Interface', glass.labelX, glass.labelY, LABEL_SIZE, 'end')}"/>
<path class="label" d="${outlineText('Objects', OBJ_X, LABEL_Y, LABEL_SIZE, 'middle')}"/>
<path class="label" d="${outlineText('Agent tools', (TOOL_X0 + TOOL_X1) / 2, LABEL_Y, LABEL_SIZE, 'middle')}"/>
</svg>
`;
}

module.exports = { output, render };
