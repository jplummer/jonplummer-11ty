/**
 * The device as the spine, for "Arguing with the agent" (2026-09-30).
 * Usage-Chan's setup runs across two screens. The device is in charge, so its lane is the
 * emphasized one and the phone's lane runs beside it, quieter. Rows are generic screen states:
 * every row defines both screens, strong where the user is looking and quiet where they aren't.
 * The accent line is the user's attention, handed to the phone and back (two handoffs). Each
 * decision sits in the lane that has the information: only the device knows whether a token is
 * stored, only the phone knows whether two PIN entries match.
 */

const path = require('path');
const { readSiteTokens, outlineText, roundedPolyline } = require('./figure-utils');

const W = 1200;
const H = 600;
const output = path.join(__dirname, '..', '..', 'src', 'assets', 'images', '2026', '09', 'device-spine.svg');

const LABEL_SIZE = 56; // near 12px at phone width; the spec's floor
const TOP = 200; // first row; the stored-token decision sits above it, at the head of the spine
const ROW_GAP = 100;
const BOX_H = 64;
const DEVICE = { x: 493, boxW: 210, pad: 30 };
const PHONE = { x: 763, boxW: 150, pad: 20 };
const DIAMOND_R = 30;
const CORNER_R = 28;

const ROWS = [0, 1, 2, 3].map((i) => TOP + i * ROW_GAP);
// Where the user is looking at each row: device, phone, phone, device
const ON_DEVICE = [true, false, false, true];

const n = (v) => Math.round(v * 10) / 10;
const rect = (cx, cy, w, h, cls) => `<rect class="${cls}" x="${n(cx - w / 2)}" y="${n(cy - h / 2)}" width="${n(w)}" height="${n(h)}"/>`;
const diamond = (cx, cy, r, cls) => `<path class="${cls}" d="M${n(cx)} ${n(cy - r)}L${n(cx + r)} ${n(cy)}L${n(cx)} ${n(cy + r)}L${n(cx - r)} ${n(cy)}Z"/>`;

function render() {
  const site = readSiteTokens();
  // As on the FigJam board: setup starts with the device checking for a stored token, before
  // its first screen. The phone checks its own two PIN entries.
  const tokenY = ROWS[0] - BOX_H / 2 - 10 - DIAMOND_R;
  const pinY = (ROWS[1] + ROWS[2]) / 2;
  const gap01 = (ROWS[0] + ROWS[1]) / 2;
  const gap23 = (ROWS[2] + ROWS[3]) / 2;
  const laneTop = tokenY - DIAMOND_R - 22;
  const laneBottom = ROWS[3] + BOX_H / 2 + 30;
  const laneY = (laneTop + laneBottom) / 2;
  const laneH = laneBottom - laneTop;

  // Attention runs down whichever lane has it and crosses only in the gaps between rows, with the
  // same smooth pair of rounded turns going over and coming back.
  const attention = roundedPolyline([
    [DEVICE.x, laneTop + 8],
    [DEVICE.x, gap01],
    [PHONE.x, gap01],
    [PHONE.x, gap23],
    [DEVICE.x, gap23],
    [DEVICE.x, laneBottom - 8],
  ], CORNER_R);

  const boxes = ROWS.map((y, i) =>
    rect(DEVICE.x, y, DEVICE.boxW, BOX_H, ON_DEVICE[i] ? 'device-on' : 'device-off') +
    rect(PHONE.x, y, PHONE.boxW, BOX_H, ON_DEVICE[i] ? 'phone-off' : 'phone-on')
  ).join('\n');

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<!-- Generated by scripts/figures/device-spine.js (pnpm run generate-figures). Don't edit by hand. -->
<style>
:root {
  color-scheme: light dark;
  /* Copied from jonplummer.css :root; pnpm run test figure-tokens fails if these drift */
  --text-color: ${site['text-color']};
  --text-color-light: ${site['text-color-light']};
  --content-background-color: ${site['content-background-color']};
  --link-color: ${site['link-color']};
}
/* Lanes are ground: a faint band in light, below the page in dark. The phone's is fainter. */
.lane-device { fill: light-dark(color-mix(in oklch, var(--text-color) 7%, transparent), oklch(14% 0.006 260deg)); }
.lane-phone { fill: light-dark(color-mix(in oklch, var(--text-color) 3%, transparent), oklch(18% 0.006 260deg)); }
/* The device's screens are the emphasized ones; the phone's are a step quieter in both states */
.device-on { fill: color-mix(in oklch, var(--text-color) 72%, var(--content-background-color)); }
.device-off { fill: color-mix(in oklch, var(--text-color) 30%, var(--content-background-color)); }
.phone-on { fill: color-mix(in oklch, var(--text-color) 50%, var(--content-background-color)); }
.phone-off { fill: color-mix(in oklch, var(--text-color) 18%, var(--content-background-color)); }
.edge { fill: none; stroke: color-mix(in oklch, var(--text-color) 45%, var(--content-background-color)); stroke-width: 3; }
.attention { fill: none; stroke: var(--link-color); stroke-width: 12; stroke-linejoin: round; }
.label { fill: var(--text-color); }
.label-quiet { fill: var(--text-color-light); }
</style>
${rect(DEVICE.x, laneY, DEVICE.boxW + 2 * DEVICE.pad, laneH, 'lane-device')}
${rect(PHONE.x, laneY, PHONE.boxW + 2 * PHONE.pad, laneH, 'lane-phone')}
<path class="edge" d="M${DEVICE.x} ${tokenY}L${DEVICE.x} ${ROWS[3]}M${PHONE.x} ${ROWS[0]}L${PHONE.x} ${ROWS[3]}"/>
<path class="attention" d="${attention}"/>
${boxes}
${diamond(DEVICE.x, tokenY, DIAMOND_R, 'device-on')}
${diamond(PHONE.x, pinY, DIAMOND_R, 'phone-on')}
<path class="label" d="${outlineText('Device', DEVICE.x, laneTop - 16, LABEL_SIZE, 'middle')}"/>
<path class="label-quiet" d="${outlineText('Phone', PHONE.x, laneTop - 16, LABEL_SIZE, 'middle')}"/>
<path class="label-quiet" d="${outlineText('Token stored?', DEVICE.x - DEVICE.boxW / 2 - DEVICE.pad - 18, tokenY + 16, LABEL_SIZE, 'end')}"/>
<path class="label-quiet" d="${outlineText('PINs match?', PHONE.x + PHONE.boxW / 2 + PHONE.pad + 18, pinY + 16, LABEL_SIZE)}"/>
</svg>
`;
}

module.exports = { output, render };
