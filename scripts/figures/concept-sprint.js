/**
 * The Concept Sprint's path, for "The Concept Sprint" (2026-05-04).
 * Immersion is a bar. The Problems diamond opens out from behind it, widest where Immersion ends,
 * because the team uncovers problems during Immersion; it closes as they catalog the problems and
 * choose the best groups. Benefits and Concept follow as diamonds that meet tip to tip, each opening
 * as the team brainstorms and closing as it chooses. Concept is wide and short. From the chosen
 * concept on, one red thread: Detail, then Test as a loop that leaves and returns where Detail ends,
 * then Pitch.
 */

const path = require('path');
const { readSiteTokens, outlineText } = require('./figure-utils');

const W = 1200;
const H = 600;
const output = path.join(__dirname, '..', '..', 'src', 'assets', 'images', '2026', '05', 'concept-sprint.svg');

const LABEL_SIZE = 56; // near 12px at phone width; the spec's floor
const CAP = 22.5; // half the label font's cap height at LABEL_SIZE, to center a label on a point

const Y = 300; // the center line

// Each diamond as [left tip, widest point, right tip, half-height]. Each right tip is the next one's left.
const PROBLEMS = [110, 300, 400, 125];
const BENEFITS = [400, 490, 580, 105];
const CONCEPT = [580, 720, 860, 50];

const BAR = [40, 300]; // Immersion, ending where the Problems diamond is widest
const BAR_H = 72;

const LOOP_X = 975; // where Detail ends and the Test loop sits on the thread
const LOOP_R = 62;
const PITCH_X = 1110;

const n = (v) => Math.round(v * 10) / 10;
const label = (text, x, y) => `<path class="label" d="${outlineText(text, n(x), n(y) + CAP, LABEL_SIZE, 'middle')}"/>`;

function diamond(name, [x0, xm, x1, h]) {
  return `<path class="diamond" id="${name}" d="M${x0} ${Y}L${xm} ${Y - h}L${x1} ${Y}L${xm} ${Y + h}Z"/>`;
}

function render() {
  const site = readSiteTokens();
  const [lx, ly] = [LOOP_X - LOOP_R, Y - LOOP_R]; // the loop's leftmost point, where it heads back down
  const parts = [
    diamond('problems', PROBLEMS),
    diamond('benefits', BENEFITS),
    diamond('concept', CONCEPT),
    // The thread from the chosen concept to Pitch
    `<path class="thread" d="M${CONCEPT[2]} ${Y}H${PITCH_X}"/>`,
    // Test: a circle sitting on the thread, run up the right side and back down the left to the same point
    `<path class="thread" d="M${LOOP_X} ${Y}A${LOOP_R} ${LOOP_R} 0 0 0 ${LOOP_X} ${Y - 2 * LOOP_R}A${LOOP_R} ${LOOP_R} 0 0 0 ${LOOP_X} ${Y}"/>`,
    `<path class="tip" d="M${lx} ${ly + 16}L${lx - 15} ${ly - 12}L${lx + 15} ${ly - 12}Z"/>`,
    `<circle class="node" cx="${PITCH_X}" cy="${Y}" r="20"/>`,
    // The bar sits in front, so the Problems diamond opens out from behind it
    `<rect class="bar" x="${BAR[0]}" y="${Y - BAR_H / 2}" width="${BAR[1] - BAR[0]}" height="${BAR_H}" rx="10"/>`,
    label('Immersion', (BAR[0] + BAR[1]) / 2, Y),
    label('Problems', PROBLEMS[1], Y - PROBLEMS[3] - 57),
    label('Benefits', BENEFITS[1], Y + BENEFITS[3] + 43),
    label('Concept', CONCEPT[1], Y - CONCEPT[3] - 57),
    label('Detail', 905, Y + 58),
    label('Test', LOOP_X, Y - 2 * LOOP_R - 52),
    label('Pitch', 1120, Y + 58),
  ];
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<!-- Generated by scripts/figures/concept-sprint.js (pnpm run generate-figures). Don't edit by hand. -->
<style>
:root {
  color-scheme: light dark;
  /* Copied from jonplummer.css :root; pnpm run test figure-tokens fails if these drift */
  --text-color: ${site['text-color']};
  --content-background-color: ${site['content-background-color']};
  --link-color: ${site['link-color']};
}
.diamond { fill: color-mix(in oklch, var(--text-color) 30%, var(--content-background-color)); stroke: color-mix(in oklch, var(--text-color) 30%, var(--content-background-color)); stroke-width: 10; stroke-linejoin: round; }
.bar { fill: color-mix(in oklch, var(--text-color) 14%, var(--content-background-color)); }
.thread { fill: none; stroke: var(--link-color); stroke-width: 8; stroke-linecap: round; stroke-linejoin: round; }
.tip, .node { fill: var(--link-color); }
.label { fill: var(--text-color); }
</style>
${parts.join('\n')}
</svg>
`;
}

module.exports = { output, render };
