/**
 * Benefit, concept, detail, for "Prototyping in a regulated environment" (2026-08-27).
 * Exploration (benefit and concept) is a wild cloud of single diamonds that AI prototyping makes
 * cheap; regulators start watching once the concept is nailed down. The cloud narrows at both
 * ends: a big benefit pan opens it, a smaller concept pan stops just short of the line, and a
 * small pan beside it is what crosses into detail. Detail is one bar under scrutiny, with a few
 * tiny, evenly spaced diamonds for the changes design control lets through.
 */

const path = require('path');
const { readSiteTokens, rng, outlineText } = require('./figure-utils');

const W = 1200;
const H = 600;
const output = path.join(__dirname, '..', '..', 'src', 'assets', 'images', '2026', '08', 'benefit-concept-detail.svg');

const LABEL_SIZE = 56; // near 12px at phone width; the spec's floor
const CY = 290;
const FREEZE = 735;
const DETAIL_END = 1140;

// The cloud lives in an ellipse from the left edge to the freeze line
const X0 = 30;
const HMAX = 215;
function envelope(x) {
  const a = (FREEZE - X0) / 2;
  const t = (x - (X0 + a)) / a;
  return Math.abs(t) >= 1 ? 0 : HMAX * Math.sqrt(1 - t * t);
}

// Big pans on the centerline, deliberately different sizes. The concept pan stops just short of
// the line; the small pan beside it is the one that touches, and the only strong one.
const BIG_BENEFIT = [205, CY, 140, 50];
const BIG_CONCEPT = [FREEZE - 22 - 92, CY - 18, 92, 34];
const TOUCH = [FREEZE - 18, CY, 18, 12];
const CHANGES = [850, 960, 1070]; // design-controlled changes on the detail bar
const CHANGE_R = 22;

const n = (v) => Math.round(v * 10) / 10;

// Handle thickness follows the 2022 single-diamond drawing, about 0.37 r
function pan([cx, cy, r, h]) {
  const t = r * 0.37 / 2;
  return `M${n(cx - r - h)} ${n(cy - t)}L${n(cx - r + t)} ${n(cy - t)}L${n(cx)} ${n(cy - r)}L${n(cx + r)} ${n(cy)}L${n(cx)} ${n(cy + r)}L${n(cx - r + t)} ${n(cy + t)}L${n(cx - r - h)} ${n(cy + t)}Z`;
}

// Stratified along x so no gap opens; each whole pan, handle included, fits inside the ellipse
function cloud(seed, count) {
  const random = rng(seed);
  const out = [];
  let tries = 0;
  while (out.length < count && tries++ < 20000) {
    const cx = 50 + ((out.length + random()) / count) * (FREEZE - 70);
    const r = Math.exp(Math.log(10) + random() * (Math.log(80) - Math.log(10)));
    const h = r * (0.15 + random() * 1.2);
    const cy = CY + (random() + random() - 1) * HMAX;
    const top = cy - r;
    const bottom = cy + r;
    const fits = [cx - r - h, cx, cx + r].every((x) => top >= CY - envelope(x) && bottom <= CY + envelope(x)) &&
      cx + r <= FREEZE - 4;
    if (!fits) continue;
    if (out.some((q) => Math.hypot(cx - q[0], cy - q[1]) < (r + q[2]) * 0.35)) continue;
    out.push([cx, cy, r, h]);
  }
  return out;
}

// Extra pans between the two big ones, so the middle of the cloud doesn't thin out
function middle(seed, count, xa, xb) {
  const random = rng(seed);
  const out = [];
  let tries = 0;
  while (out.length < count && tries++ < 20000) {
    const cx = xa + random() * (xb - xa);
    const r = Math.exp(Math.log(14) + random() * (Math.log(60) - Math.log(14)));
    const h = r * (0.15 + random() * 1.0);
    const cy = CY + (random() + random() - 1) * HMAX * 0.8;
    if (cy - r < CY - envelope(cx) || cy + r > CY + envelope(cx)) continue;
    out.push([cx, cy, r, h]);
  }
  return out;
}

function crowd() {
  const rest = [...cloud(5, 10), ...middle(13, 5, 330, 470)].filter((p) => p[2] < 70);
  return [BIG_BENEFIT, BIG_CONCEPT, ...rest].sort((a, b) => b[2] - a[2]);
}

function render() {
  const site = readSiteTokens();
  const bar = `M${FREEZE} ${CY - 10}H${DETAIL_END}V${CY + 10}H${FREEZE}Z` +
    CHANGES.map((x) => `M${x - CHANGE_R} ${CY}L${x} ${CY - CHANGE_R}L${x + CHANGE_R} ${CY}L${x} ${CY + CHANGE_R}Z`).join('');

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<!-- Generated by scripts/figures/benefit-concept-detail.js (pnpm run generate-figures). Don't edit by hand. -->
<style>
:root {
  color-scheme: light dark;
  /* Copied from jonplummer.css :root; pnpm run test figure-tokens fails if these drift */
  --text-color: ${site['text-color']};
  --content-background-color: ${site['content-background-color']};
  --link-color: ${site['link-color']};
  --pan: color-mix(in oklch, var(--text-color) 45%, var(--content-background-color));
  --strong: color-mix(in oklch, var(--text-color) 70%, var(--content-background-color));
}
/* Scrutiny is ground: a faint band in light, a shadow below the page in dark */
.scrutiny { fill: light-dark(color-mix(in oklch, var(--text-color) 7%, transparent), oklch(12% 0.006 260deg)); }
/* light-dark() takes colors only, so alpha that differs by mode lives in the colors */
.pan { fill: light-dark(color-mix(in oklch, var(--pan) 26%, transparent), color-mix(in oklch, var(--pan) 55%, transparent)); }
.strong { fill: var(--strong); }
.freeze { stroke: var(--link-color); stroke-width: 4; stroke-dasharray: 18 12; }
.label { fill: var(--text-color); }
.label-accent { fill: var(--link-color); }
</style>
<rect class="scrutiny" x="${FREEZE}" y="60" width="${W - FREEZE - 30}" height="480"/>
${crowd().map((p) => `<path class="pan" d="${pan(p)}"/>`).join('\n')}
<path class="strong" d="${pan(TOUCH)}"/>
<path class="strong" d="${bar}"/>
<line class="freeze" x1="${FREEZE}" x2="${FREEZE}" y1="60" y2="540"/>
<path class="label" d="${outlineText('Benefit', 250, 570, LABEL_SIZE, 'middle')}"/>
<path class="label" d="${outlineText('Concept', 545, 570, LABEL_SIZE, 'middle')}"/>
<path class="label" d="${outlineText('Detail', 950, 570, LABEL_SIZE, 'middle')}"/>
<path class="label label-accent" d="${outlineText('Concept', FREEZE + 20, 120, LABEL_SIZE)}"/>
<path class="label label-accent" d="${outlineText('nailed down', FREEZE + 20, 178, LABEL_SIZE)}"/>
</svg>
`;
}

module.exports = { output, render };
