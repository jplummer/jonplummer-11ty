#!/usr/bin/env node

/**
 * Writes a light and a dark copy of each generated figure with every color resolved to a plain
 * hex fill, for import into the Figma catalog (see the lead figure spec). Figma's SVG import
 * ignores the figure's <style>, so its classes, var(), light-dark(), and color-mix() would all come
 * in black. Chrome computes the styles, and each computed color is converted to sRGB hex.
 *
 * pnpm run flatten-figures [name ...]   e.g. pnpm run flatten-figures two-systems
 * Output: .cache/figma-figures/<name>-light.svg and <name>-dark.svg
 */

const fs = require('fs');
const path = require('path');
const puppeteer = require('puppeteer');

const ROOT = path.join(__dirname, '..', '..');
const IMAGES = path.join(ROOT, 'src', 'assets', 'images');
const OUT = path.join(ROOT, '.cache', 'figma-figures');

function findFigures(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return findFigures(full);
    if (!entry.name.endsWith('.svg')) return [];
    return fs.readFileSync(full, 'utf8').includes('Generated by scripts/figures/') ? [full] : [];
  });
}

// Runs in the page: resolve every element's computed colors into attributes, then drop the CSS
function flatten() {
  // Relative color syntax makes Chrome report the computed color as sRGB floats, alpha included.
  // A canvas readback would round translucent colors badly.
  const svg = document.querySelector('svg');
  const probe = document.createElementNS('http://www.w3.org/2000/svg', 'rect');
  svg.appendChild(probe);
  const toHex = (color) => {
    probe.style.fill = `color(from ${color} srgb r g b / alpha)`;
    const computed = getComputedStyle(probe).fill;
    const m = computed.match(/color\(srgb ([-\d.e]+) ([-\d.e]+) ([-\d.e]+)(?: \/ ([\d.e]+))?\)/);
    if (!m) throw new Error(`Can't read color ${color} (computed ${computed})`);
    const h = (v) => Math.round(Math.min(1, Math.max(0, +v)) * 255).toString(16).padStart(2, '0');
    return { hex: `#${h(m[1])}${h(m[2])}${h(m[3])}`, alpha: m[4] === undefined ? 1 : Math.round(+m[4] * 1000) / 1000 };
  };
  const background = toHex('var(--content-background-color)').hex;

  const SHAPES = new Set(['path', 'rect', 'line', 'circle', 'ellipse', 'polygon', 'polyline']);
  for (const el of svg.querySelectorAll('*')) {
    if (el === probe) continue;
    const cs = getComputedStyle(el);
    if (el.tagName === 'stop') {
      const c = toHex(cs.stopColor);
      el.setAttribute('stop-color', c.hex);
      if (c.alpha < 1) el.setAttribute('stop-opacity', c.alpha);
    } else if (SHAPES.has(el.tagName)) {
      for (const prop of ['fill', 'stroke']) {
        const value = cs[prop];
        if (!value || value === 'none') {
          el.setAttribute(prop, 'none');
        } else if (value.startsWith('url(')) {
          el.setAttribute(prop, value.replace(/url\("?[^#]*#([^")]+)"?\)/, 'url(#$1)'));
        } else {
          const c = toHex(value);
          el.setAttribute(prop, c.hex);
          if (c.alpha < 1) el.setAttribute(`${prop}-opacity`, c.alpha);
        }
      }
      if (cs.stroke !== 'none') {
        el.setAttribute('stroke-width', parseFloat(cs.strokeWidth));
        if (cs.strokeDasharray !== 'none') el.setAttribute('stroke-dasharray', cs.strokeDasharray.replace(/px/g, ''));
        if (cs.strokeLinecap !== 'butt') el.setAttribute('stroke-linecap', cs.strokeLinecap);
        if (cs.strokeLinejoin !== 'miter') el.setAttribute('stroke-linejoin', cs.strokeLinejoin);
      }
      if (cs.opacity !== '1') el.setAttribute('opacity', cs.opacity);
    }
    el.removeAttribute('class');
  }
  probe.remove();
  svg.querySelectorAll('style').forEach((s) => s.remove());
  return { svg: svg.outerHTML.replace(/<!--[\s\S]*?-->\n?/g, ''), background };
}

(async () => {
  const only = new Set(process.argv.slice(2));
  const figures = findFigures(IMAGES).filter((f) => !only.size || only.has(path.basename(f, '.svg')));
  if (!figures.length) {
    console.error(`No generated figures match: ${[...only].join(', ')}`);
    process.exit(1);
  }
  fs.mkdirSync(OUT, { recursive: true });
  const browser = await puppeteer.launch();
  try {
    const page = await browser.newPage();
    for (const file of figures) {
      const name = path.basename(file, '.svg');
      const source = fs.readFileSync(file, 'utf8');
      for (const mode of ['light', 'dark']) {
        await page.emulateMediaFeatures([{ name: 'prefers-color-scheme', value: mode }]);
        await page.setContent(`<!doctype html><body style="margin:0">${source}</body>`);
        const { svg, background } = await page.evaluate(flatten);
        const out = path.join(OUT, `${name}-${mode}.svg`);
        fs.writeFileSync(out, svg);
        console.log(`✅ ${path.relative(ROOT, out)}  (frame fill ${background})`);
      }
    }
  } finally {
    await browser.close();
  }
})();
