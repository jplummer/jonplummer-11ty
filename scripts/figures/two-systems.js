/**
 * Two systems, for "The complaints that wouldn't go away" (2026-07-24).
 * The design system in Figma above, the design system in code below, which were supposed to be
 * one system. A component is a box with one cell per variant; a component that matches across the
 * two is tied to its twin. Each kind of drift the post found appears once, in red: a component only
 * in Figma, values that differ (≠), a variant missing in code, a component only in code.
 */

const path = require('path');
const { readSiteTokens, outlineText } = require('./figure-utils');

const W = 1200;
const H = 600;
const output = path.join(__dirname, '..', '..', 'src', 'assets', 'images', '2026', '07', 'two-systems.svg');

const LABEL_SIZE = 56; // near 12px at phone width; the spec's floor
const BASELINE = 20; // drops a label's baseline so its capitals center on a row
const FIGMA_Y = 170;
const CODE_Y = 440;
const BOX_W = 136;
const BOX_H = 104;
const CELL = 32;
const CELL_GAP = 10;
const CELL_DROP = 18; // cells sit in the lower half of the box

// Left to right: matched, only in Figma, values differ, variant missing in code, only in code, matched
const COLUMNS = [
  { x: 262, kind: 'match' },
  { x: 435, kind: 'figmaOnly' },
  { x: 608, kind: 'drift' },
  { x: 782, kind: 'variant' },
  { x: 955, kind: 'codeOnly' },
  { x: 1128, kind: 'match' },
];

const n = (v) => Math.round(v * 10) / 10;
const rect = (cx, cy, w, h, cls) => `<rect class="${cls}" x="${n(cx - w / 2)}" y="${n(cy - h / 2)}" width="${n(w)}" height="${n(h)}"/>`;

// A component with `variants` cells; `missing` more cells are slots this side lacks
function component(cx, cy, variants, missing = 0) {
  const count = variants + missing;
  const span = count * CELL + (count - 1) * CELL_GAP;
  let out = rect(cx, cy, BOX_W, BOX_H, 'component');
  for (let i = 0; i < count; i++) {
    const x = cx - span / 2 + CELL / 2 + i * (CELL + CELL_GAP);
    out += rect(x, cy + CELL_DROP, CELL, CELL, i < variants ? 'variant' : 'variant-missing');
  }
  return out;
}

const absent = (cx, cy) => rect(cx, cy, BOX_W - 6, BOX_H - 6, 'absent');
const tie = (cx) => `<path class="tie" d="M${cx} ${FIGMA_Y + BOX_H / 2}V${CODE_Y - BOX_H / 2}"/>`;

// Big Shoulders has no ≠, so it's drawn: two bars and a slash at about the labels' stroke weight
function notEqual(cx, cy) {
  return `<path class="not-equal" d="M${cx - 17} ${cy - 8}H${cx + 17}M${cx - 17} ${cy + 8}H${cx + 17}M${cx + 9} ${cy - 20}L${cx - 9} ${cy + 20}"/>`;
}

function column({ x, kind }) {
  switch (kind) {
    case 'match':
      return tie(x) + component(x, FIGMA_Y, 2) + component(x, CODE_Y, 2);
    case 'figmaOnly':
      return component(x, FIGMA_Y, 1) + absent(x, CODE_Y);
    case 'codeOnly':
      return absent(x, FIGMA_Y) + component(x, CODE_Y, 2);
    case 'variant':
      return tie(x) + component(x, FIGMA_Y, 3) + component(x, CODE_Y, 2, 1);
    case 'drift':
      return notEqual(x, (FIGMA_Y + CODE_Y) / 2) + component(x, FIGMA_Y, 1) + component(x, CODE_Y, 1);
    default:
      throw new Error(`unknown column kind ${kind}`);
  }
}

function render() {
  const site = readSiteTokens();
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<!-- Generated by scripts/figures/two-systems.js (pnpm run generate-figures). Don't edit by hand. -->
<style>
:root {
  color-scheme: light dark;
  /* Copied from jonplummer.css :root; pnpm run test figure-tokens fails if these drift */
  --text-color: ${site['text-color']};
  --content-background-color: ${site['content-background-color']};
  --link-color: ${site['link-color']};
}
.component { fill: color-mix(in oklch, var(--text-color) 70%, var(--content-background-color)); }
.variant { fill: var(--content-background-color); }
/* Solid, not dashed: dashes this small broke into specks at phone width */
.variant-missing { fill: var(--content-background-color); stroke: var(--link-color); stroke-width: 7; }
.absent { fill: none; stroke: var(--link-color); stroke-width: 5; stroke-dasharray: 14 10; }
.tie { fill: none; stroke: color-mix(in oklch, var(--text-color) 45%, var(--content-background-color)); stroke-width: 6; }
.not-equal { fill: none; stroke: var(--link-color); stroke-width: 7; }
.label { fill: var(--text-color); }
</style>
${COLUMNS.map(column).join('\n')}
<path class="label" d="${outlineText('Figma', 40, FIGMA_Y + BASELINE, LABEL_SIZE)}"/>
<path class="label" d="${outlineText('Code', 40, CODE_Y + BASELINE, LABEL_SIZE)}"/>
</svg>
`;
}

module.exports = { output, render };
