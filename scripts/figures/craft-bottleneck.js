/**
 * The next bottleneck, for "How do you raise the level of craft?" (2026-07-30).
 * Craft runs through a channel from designed to shipped, pinched at points in the lifecycle.
 * What gets through can't be wider than the narrowest pinch it has passed. Alignment, the
 * problem in the interview story, restricts some; Specs is a pinch too, but wider than what
 * Alignment already lets through, so it costs nothing; Polish is the bottleneck, marked by its red
 * walls.
 * The pinch names come from the post's failure modes.
 */

const path = require('path');
const { readSiteTokens, outlineText } = require('./figure-utils');

const W = 1200;
const H = 600;
const output = path.join(__dirname, '..', '..', 'src', 'assets', 'images', '2026', '07', 'craft-bottleneck.svg');

const LABEL_SIZE = 56; // near 12px at phone width; the spec's floor
const CY = 290;
const X0 = 240;
const X1 = 975;
const FULL = 118; // the channel's half-height between pinches
const FLAT = 46; // length of each pinch's narrow section
const SHOULDER = 30; // length of each angled shoulder
const DESIGNED = 80; // the flow's half-height as designed, a little inside the channel
const GAP = 14; // the flow keeps this clear of any wall it passes

const PINCHES = [
  { x: 360, h: 78, name: 'Alignment' }, // restricts some
  { x: 590, h: 82, name: 'Specs' }, // a pinch, but wider than what Alignment already lets through
  { x: 858, h: 52, name: 'Polish' }, // the bottleneck
];

const n = (v) => Math.round(v * 10) / 10;

function capacity(x) {
  let c = FULL;
  for (const k of PINCHES) {
    const d = Math.abs(x - k.x);
    if (d <= FLAT / 2) c = Math.min(c, k.h);
    else if (d <= FLAT / 2 + SHOULDER) c = Math.min(c, k.h + (FULL - k.h) * (d - FLAT / 2) / SHOULDER);
  }
  return c;
}

// What gets through: as designed, until a wall it has passed is narrower than that
function carried(x) {
  let m = DESIGNED;
  for (let t = X0; t <= x; t += 2) m = Math.min(m, capacity(t) - GAP);
  return m;
}

function band(f) {
  const top = [];
  const bottom = [];
  for (let x = X0; x <= X1; x += 2) {
    const h = f(x);
    top.push(`${x} ${n(CY - h)}`);
    bottom.unshift(`${x} ${n(CY + h)}`);
  }
  return `M${[...top, ...bottom].join('L')}Z`;
}

function render() {
  const site = readSiteTokens();
  const neck = PINCHES.reduce((a, b) => (b.h < a.h ? b : a));
  const walls = `M${neck.x - FLAT / 2} ${CY - neck.h}L${neck.x + FLAT / 2} ${CY - neck.h}` +
    `M${neck.x - FLAT / 2} ${CY + neck.h}L${neck.x + FLAT / 2} ${CY + neck.h}`;

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<!-- Generated by scripts/figures/craft-bottleneck.js (pnpm run generate-figures). Don't edit by hand. -->
<style>
:root {
  color-scheme: light dark;
  /* Copied from jonplummer.css :root; pnpm run test figure-tokens fails if these drift */
  --text-color: ${site['text-color']};
  --text-color-light: ${site['text-color-light']};
  --content-background-color: ${site['content-background-color']};
  --link-color: ${site['link-color']};
}
/* The channel is ground: faint in light, below the page in dark */
.channel { fill: light-dark(color-mix(in oklch, var(--text-color) 9%, transparent), oklch(14% 0.006 260deg)); }
.flow { fill: color-mix(in oklch, var(--text-color) 70%, var(--content-background-color)); }
.bottleneck { fill: none; stroke: var(--link-color); stroke-width: 6; }
.label { fill: var(--text-color-light); }
</style>
<path class="channel" d="${band(capacity)}"/>
<path class="flow" d="${band(carried)}"/>
<path class="bottleneck" d="${walls}"/>
${PINCHES.map((k) => `<path class="label" d="${outlineText(k.name, k.x, CY + FULL + 64, LABEL_SIZE, 'middle')}"/>`).join('\n')}
<path class="label" d="${outlineText('Designed', X0 - 16, CY + 18, LABEL_SIZE, 'end')}"/>
<path class="label" d="${outlineText('Shipped', X1 + 16, CY + 18, LABEL_SIZE)}"/>
</svg>
`;
}

module.exports = { output, render };
