/**
 * Fragmented and coordinated, for "Toward coordinated experience" (2025-07-27).
 * Two three-step workflows. In the fragmented one the system advances you from the first step to
 * the second, then nothing does: where the path should leave the second step there's only a
 * question, and a stub reaches a third step that's out of reach (quiet). In the coordinated one
 * every step advances to the next, and the middle step presents the capability it needs as a
 * module inside it instead of sending you elsewhere.
 */

const path = require('path');
const { readSiteTokens, outlineText } = require('./figure-utils');

const W = 1200;
const H = 600;
const output = path.join(__dirname, '..', '..', 'src', 'assets', 'images', '2025', '07', 'coordinated-experience.svg');

const LABEL_SIZE = 56; // near 12px at phone width; the spec's floor
const BASELINE = 20; // drops a label's baseline so its capitals center on a row
const TITLE_X = 40;
const ROW_X0 = 420;
const ROW_X1 = 1150;
const FRAGMENTED_Y = 165;
const COORDINATED_Y = 435;
const BOX_W = 135;
const BOX_H = 108;
const MODULE_W = 189; // the middle step of the coordinated row, which holds the module
const MODULE_H = 162;

const n = (v) => Math.round(v * 10) / 10;
const rect = (cx, cy, w, h, cls) => `<rect class="${cls}" x="${n(cx - w / 2)}" y="${n(cy - h / 2)}" width="${n(w)}" height="${n(h)}"/>`;
const line = (x0, x1, y, cls) => `<path class="${cls}" d="M${n(x0)} ${y}H${n(x1)}"/>`;

const XS = [ROW_X0 + BOX_W / 2, (ROW_X0 + ROW_X1) / 2, ROW_X1 - BOX_W / 2];

function fragmented(y) {
  // Where the path should leave the second step there's only a question; a stub reaches the third
  const gap0 = XS[1] + BOX_W / 2;
  const gap1 = XS[2] - BOX_W / 2;
  const span = gap1 - gap0;
  return [
    line(XS[0] + BOX_W / 2, XS[1] - BOX_W / 2, y, 'go'),
    line(gap0 + span * 0.7, gap1, y, 'barrier'),
    rect(XS[0], y, BOX_W, BOX_H, 'step'),
    rect(XS[1], y, BOX_W, BOX_H, 'step'),
    rect(XS[2], y, BOX_W, BOX_H, 'step-quiet'),
    `<path class="label-accent" d="${outlineText('?', gap0 + span * 0.2, y + BASELINE, LABEL_SIZE, 'middle')}"/>`,
  ].join('\n');
}

function coordinated(y) {
  const inset = y + 21.6;
  return [
    line(XS[0] + BOX_W / 2, XS[1] - MODULE_W / 2, y, 'go'),
    line(XS[1] + MODULE_W / 2, XS[2] - BOX_W / 2, y, 'go'),
    rect(XS[0], y, BOX_W, BOX_H, 'step'),
    rect(XS[1], y, MODULE_W, MODULE_H, 'step'),
    rect(XS[2], y, BOX_W, BOX_H, 'step'),
    // The capability, presented as a module inside the step that needs it
    rect(XS[1], inset, 121.5, 67.5, 'module-well'),
    rect(XS[1], inset, 94.5, 43.2, 'step-quiet'),
  ].join('\n');
}

function render() {
  const site = readSiteTokens();
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<!-- Generated by scripts/figures/coordinated-experience.js (pnpm run generate-figures). Don't edit by hand. -->
<style>
:root {
  color-scheme: light dark;
  /* Copied from jonplummer.css :root; pnpm run test figure-tokens fails if these drift */
  --text-color: ${site['text-color']};
  --content-background-color: ${site['content-background-color']};
  --link-color: ${site['link-color']};
}
.step { fill: color-mix(in oklch, var(--text-color) 70%, var(--content-background-color)); }
.step-quiet { fill: color-mix(in oklch, var(--text-color) 30%, var(--content-background-color)); }
.module-well { fill: var(--content-background-color); }
.go { fill: none; stroke: color-mix(in oklch, var(--text-color) 70%, var(--content-background-color)); stroke-width: 8; }
.barrier { fill: none; stroke: var(--link-color); stroke-width: 8; }
.label { fill: var(--text-color); }
.label-accent { fill: var(--link-color); }
</style>
${fragmented(FRAGMENTED_Y)}
${coordinated(COORDINATED_Y)}
<path class="label" d="${outlineText('Fragmented', TITLE_X, FRAGMENTED_Y + BASELINE, LABEL_SIZE)}"/>
<path class="label" d="${outlineText('Coordinated', TITLE_X, COORDINATED_Y + BASELINE, LABEL_SIZE)}"/>
</svg>
`;
}

module.exports = { output, render };
