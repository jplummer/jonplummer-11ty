/**
 * Three horizons, for "Teaching a product team to do discovery" (2026-10-28).
 * Redrawn from a 2022 Cayuse slide: near crag, middle ridges falling into a valley,
 * far range in haze. Horizon three takes the accent because the post is about it.
 */

const path = require('path');
const { readSiteTokens, ridge, ridgePath, outlineText } = require('./figure-utils');

const W = 1200;
const H = 600;
const output = path.join(__dirname, '..', '..', 'src', 'assets', 'images', '2026', '10', 'three-horizons.svg');

// Far range: the left end sinks gently into the middle ridge instead of meeting it head-on
const FAR = [[0, 282], [70, 274], [150, 262], [300, 286], [470, 270], [640, 292], [820, 262], [1000, 280], [1200, 255]];
// Middle ridge: shallow descent on the left keeps the crossing with the far range at a low angle
const MID = [[0, 252], [90, 266], [170, 290], [260, 330], [420, 392], [560, 410], [700, 392], [860, 360], [1000, 330], [1200, 300]];
// Near crag: rises to the right, with the spire left of center
const NEAR = [[0, 520], [180, 505], [330, 470], [420, 440], [470, 430], [500, 330], [525, 325], [560, 345], [575, 470], [620, 440], [700, 330], [800, 250], [920, 215], [1060, 195], [1200, 170]];

const LABEL_SIZE = 56; // near 12px at phone width; the spec's floor

function render() {
  const site = readSiteTokens();
  const far = ridgePath(ridge(FAR, 0.35, 5, 3), W, H);
  const mid = ridgePath(ridge(MID, 0.4, 5, 11), W, H);
  const near = ridgePath(ridge(NEAR, 0.6, 4, 29), W, H);

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<!-- Generated by scripts/figures/three-horizons.js (pnpm run generate-figures). Don't edit by hand. -->
<style>
:root {
  color-scheme: light dark;
  /* Copied from jonplummer.css :root; pnpm run test figure-tokens fails if these drift */
  --text-color: ${site['text-color']};
  --content-background-color: ${site['content-background-color']};
  --link-color: ${site['link-color']};
  /* Light is daylight haze, near ridge darkest. Dark is dusk: near ridge darker than the page, far range glows. */
  --ridge-near: light-dark(color-mix(in oklch, var(--text-color) 88%, var(--content-background-color)), oklch(11% 0.006 260deg));
  --ridge-mid: light-dark(color-mix(in oklch, var(--text-color) 52%, var(--content-background-color)), oklch(20% 0.008 260deg));
  --ridge-far: light-dark(color-mix(in oklch, var(--text-color) 22%, var(--content-background-color)), oklch(44% 0.01 260deg));
  --haze: light-dark(color-mix(in oklch, var(--text-color) 8%, var(--content-background-color)), oklch(34% 0.008 260deg));
  --ridge-near-base: color-mix(in oklch, var(--ridge-near) 80%, var(--ridge-mid));
  /* oklab in dark: an oklch mix of red into blue-grey swings through purple */
  --ridge-accent: light-dark(color-mix(in oklch, var(--link-color) 30%, var(--content-background-color)), color-mix(in oklab, var(--link-color) 35%, var(--ridge-far)));
  --label-on-ridge: light-dark(var(--content-background-color), var(--text-color));
}
.stop-field { stop-color: var(--content-background-color); }
.stop-haze { stop-color: var(--haze); }
.stop-ridge-near { stop-color: var(--ridge-near); }
.stop-ridge-near-base { stop-color: var(--ridge-near-base); }
.stop-ridge-mid { stop-color: var(--ridge-mid); }
.stop-ridge-far { stop-color: var(--ridge-far); }
.stop-ridge-accent { stop-color: var(--ridge-accent); }
.label { fill: var(--text-color); }
.label-on-ridge { fill: var(--label-on-ridge); }
.label-accent { fill: var(--link-color); }
</style>
<defs>
<linearGradient id="sky" x1="0" y1="0" x2="0" y2="320" gradientUnits="userSpaceOnUse"><stop class="stop-field"/><stop offset="1" class="stop-haze"/></linearGradient>
<linearGradient id="far" x1="0" y1="250" x2="0" y2="330" gradientUnits="userSpaceOnUse"><stop class="stop-ridge-accent"/><stop offset="1" class="stop-haze"/></linearGradient>
<linearGradient id="mid" x1="0" y1="250" x2="0" y2="470" gradientUnits="userSpaceOnUse"><stop class="stop-ridge-mid"/><stop offset="1" class="stop-ridge-far"/></linearGradient>
<linearGradient id="near" x1="0" y1="170" x2="0" y2="600" gradientUnits="userSpaceOnUse"><stop class="stop-ridge-near"/><stop offset="1" class="stop-ridge-near-base"/></linearGradient>
</defs>
<rect width="${W}" height="320" fill="url(#sky)"/>
<path fill="url(#far)" d="${far}"/>
<path fill="url(#mid)" d="${mid}"/>
<path fill="url(#near)" d="${near}"/>
<path class="label label-on-ridge" d="${outlineText('Horizon 1: Ship', 40, 578, LABEL_SIZE)}"/>
<path class="label" d="${outlineText('Horizon 2: Choose', 36, 378, LABEL_SIZE)}"/>
<path class="label label-accent" d="${outlineText('Horizon 3: Discover', 180, 236, LABEL_SIZE)}"/>
</svg>
`;
}

module.exports = { output, render };
